#2.Menjalankan binary_search_trace() untuk target yang berada di sekitar tengah data
def binary_search_trace(data, target):
    low = 0
    high = len(data) - 1
    while low <= high:
        mid = (low + high) // 2
        print("Mengecek indeks", mid, "nilai", data[mid])
        if data[mid] == target:
            print("Target ditemukan pada indeks", mid)
            return mid
        elif data[mid] < target:
            low = mid + 1
        else:
            high = mid - 1
    print("Target tidak ditemukan")
    return -1
